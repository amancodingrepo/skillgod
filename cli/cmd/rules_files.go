// writeCursorRules writes the project-level always-applied rule Cursor
// guarantees delivery of. cwd is the directory `sg init` was run from.
func writeCursorRules(cwd string) (ruleFileStatus, error) {
	path := filepath.Join(cwd, ".cursor", "rules", "skillgod.mdc")
	return writeAdditiveRuleFile(path, cursorRuleContent)
}

// writeWindsurfRules writes the workspace-level always_on rule for
// Windsurf / Devin Desktop. Writes the PREFERRED current path
// (.devin/rules/skillgod.md) first, then the legacy fallback
// (.windsurf/rules/skillgod.md) — both are still read by current builds during
// the Windsurf→Devin Desktop transition, so writing both guarantees the rule
// fires regardless of which build the user is running. Returns a status per
// path written so `sg init` can report both.
func writeWindsurfRules(cwd string) ([]ruleFileStatus, error) {
	var out []ruleFileStatus
	devinPath := filepath.Join(cwd, ".devin", "rules", "skillgod.md")
	ds, err := writeAdditiveRuleFile(devinPath, devinRuleContent)
	if err != nil {
		return out, err
	}
	out = append(out, ds)
	legacyPath := filepath.Join(cwd, ".windsurf", "rules", "skillgod.md")
	ls, err := writeAdditiveRuleFile(legacyPath, windsurfRuleContent)
	if err != nil {
		return out, err
	}
	out = append(out, ls)
	return out, nil
}

// writeAntigravityRules writes the workspace-level always_on rule for
// Antigravity. See antigravityRuleContent's comment — unverified against a
// live install, unlike the Cursor/Windsurf equivalents.
func writeAntigravityRules(cwd string) (ruleFileStatus, error) {
	path := filepath.Join(cwd, ".agent", "rules", "skillgod.md")
	return writeAdditiveRuleFile(path, antigravityRuleContent)
}
